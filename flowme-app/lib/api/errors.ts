import { NextResponse } from 'next/server';

export enum ErrorCode {
  VALIDATION_ERROR = 'VALIDATION_ERROR',
  UNAUTHORIZED = 'UNAUTHORIZED',
  FEATURE_LOCKED = 'FEATURE_LOCKED',
  NOT_FOUND = 'NOT_FOUND',
  GOOGLE_AUTH_MISSING = 'GOOGLE_AUTH_MISSING',
  GOOGLE_TOKEN_REFRESH_FAILED = 'GOOGLE_TOKEN_REFRESH_FAILED',
  GOOGLE_API_ERROR = 'GOOGLE_API_ERROR',
  SLACK_AUTH_MISSING = 'SLACK_AUTH_MISSING',
  SLACK_TOKEN_REFRESH_FAILED = 'SLACK_TOKEN_REFRESH_FAILED',
  SUPABASE_ERROR = 'SUPABASE_ERROR',
  PAYMENT_PROVIDER_ERROR = 'PAYMENT_PROVIDER_ERROR',
  SUPPORT_MESSAGE_INVALID = 'SUPPORT_MESSAGE_INVALID',
  SUPPORT_UNAVAILABLE = 'SUPPORT_UNAVAILABLE',
  CANCELLATION_FUNNEL_STEP_REQUIRED = 'CANCELLATION_FUNNEL_STEP_REQUIRED',
  CANCELLATION_FUNNEL_REQUIRED = 'CANCELLATION_FUNNEL_REQUIRED',
  CANCELLATION_REASON_REQUIRED = 'CANCELLATION_REASON_REQUIRED',
  CANCELLATION_DETAILS_INVALID = 'CANCELLATION_DETAILS_INVALID',
  CANCELLATION_ALREADY_OPEN = 'CANCELLATION_ALREADY_OPEN',
  CANCELLATION_CREATE_FAILED = 'CANCELLATION_CREATE_FAILED',
  INTERNAL_ERROR = 'INTERNAL_ERROR',
}

export function apiSuccess(data: any = {}) {
  return NextResponse.json({ ok: true, ...data }, { status: 200 });
}

export function apiError(code: ErrorCode, message: string, status: number = 400, details: Record<string, unknown> = {}) {
  return NextResponse.json(
    { ok: false, error: { code, message }, ...details },
    { status }
  );
}
