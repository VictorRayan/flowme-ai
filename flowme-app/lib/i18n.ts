export type UiLang = 'en' | 'pt';

export function resolveUiLang(input: string | null | undefined): UiLang {
  return input === 'pt' ? 'pt' : 'en';
}

export function getUiLang(): UiLang {
  if (typeof window === 'undefined') return 'en';
  return resolveUiLang(localStorage.getItem('ui_language'));
}

